#!/bin/bash
# Regenerates src/mappreview.cpp: an 112x63 thumbnail of every listed map for the main menu's map page.
# Needs ./crumplezone built and ImageMagick (convert). Offscreen rendering is fine. Usage: tools/mappreviews.sh
set -e
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
out=src/mappreview.cpp
{
  echo "// Thumbnails of the maps for the main menu (generated by tools/mappreviews.sh: 112x63 RGB, base64, one per MapId)."
  echo '#include "mainmenudraw.h"'
  echo '#include <string>'
  echo 'namespace mainmenu {'
  echo 'namespace {'
  echo 'const char* const kData[] = {'
} > $out
for m in 0 1 2 3 4 5; do
  SDL_VIDEODRIVER=offscreen timeout -k 10 300 ./crumplezone --map $m --size 960,540 --photo --time 17.6 --quality 1 --no-pad --orbit $([ $m = 0 ] && echo 120,12,34 || echo 35,14,32) \
      --shot-prefix $tmp/m$m --shot-frames 150 > $tmp/m$m.log 2>&1 || true
  ppm=$(ls $tmp/m${m}_*.ppm | head -1)
  convert "$ppm" -filter Triangle -resize 112x63! -depth 8 rgb:$tmp/m$m.rgb
  echo "\"$(base64 -w0 $tmp/m$m.rgb)\"," >> $out
done
cat >> $out <<'EOT'
};
int b64(char c) { return c >= 'A' && c <= 'Z' ? c - 'A' : c >= 'a' && c <= 'z' ? c - 'a' + 26 : c >= '0' && c <= '9' ? c - '0' + 52 : c == '+' ? 62 : 63; }
}  // namespace

const unsigned char* mapPreview(int map) {
    static std::string decoded[sizeof kData / sizeof kData[0]];
    if (map < 0 || map >= (int)(sizeof kData / sizeof kData[0])) return nullptr;
    std::string& d = decoded[map];
    if (d.empty()) {
        const char* s = kData[map];
        int acc = 0, bits = 0;
        for (; *s && *s != '='; s++) {
            acc = (acc << 6) | b64(*s), bits += 6;
            if (bits >= 8) bits -= 8, d.push_back((char)((acc >> bits) & 255));
        }
    }
    return d.size() == (size_t)kPreviewW * kPreviewH * 3 ? (const unsigned char*)d.data() : nullptr;
}
}  // namespace mainmenu
EOT
rm -rf $tmp
echo "wrote $out"

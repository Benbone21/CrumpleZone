// The procedural world (docs/superpowers/specs/2026-10-25-procedural-world-design.md): an endless land made from a seed, a
// fresh one for every new world.
//
// Everything here is a pure function of (seed, global position). Global positions are whole metres from the world's origin
// (int64: x east, z north) plus a sub-metre offset. Only + - * /, sqrt and floor go into the numbers (no libm sin/cos/exp/pow),
// so every machine makes the same bytes from the same seed.
//
// The game never holds the whole land: World(MAP_PROCEDURAL) is a WINDOW of it, kWindowHalf each way round
// World::proc.ox/oz (a chunk corner), built from 64 m chunks (cached here). The window slides as you drive (procstream.h):
// a new one round you is built on a worker, and everything moves by the whole-metre offset on the frame it goes in.
// So local coordinates never grow, however far out you are.
#pragma once
#include <cstdint>
#include <memory>
#include <string>
#include <vector>

#include "mathx.h"

class World;
class Sim;
struct MapPlace;

namespace proc {

constexpr int kGenVersion = 1;          // bump when any generated byte changes (multiplayer refuses another version's worlds)
constexpr int kChunk = 64;              // m: a chunk's side (and the CellTiles tile's: celltiles.h)
constexpr double kWindowHalf = 1536;    // the window: 3072 m a side (48 chunks), so 3073 cells
constexpr double kSlide = 512;          // it slides once the focus is this far from its centre (either axis)
constexpr int kCell = 512;              // m: the trail lattice's cell (one node, one place, each)

enum Biome { PB_MEADOW, PB_FOREST, PB_BADLANDS, PB_MOUNTAINS, PB_DUNES, PB_COUNT };
const char* biomeName(int b);

// Floor division (toward minus infinity), for global coordinates that may be negative.
inline int64_t floorDiv(int64_t a, int64_t b) { return a >= 0 ? a / b : -((-a + b - 1) / b); }

// What's placed in a chunk, at offsets from its corner (x, z in metres within [0, 64)).
struct TreeSpec {
    float x, z, height, radius, tint;
    uint8_t kind;  // 0 pine, 1 broadleaf, 2 snag
};
struct RockSpec {
    float x, z, rx, ry, rz, top, tint;
    uint32_t seed;
};
struct BushSpec {
    float x, z, u, tint;
    uint8_t habitat, edge;
};
struct LogSpec {
    float ax, az, bx, bz, r;
};

// A chunk of land: its 64 x 64 cells (cell (a, b) at global (cx * 64 + a, cz * 64 + b)) and what stands on it.
struct Chunk {
    int64_t cx = 0, cz = 0;
    std::vector<float> h;               // heights, a * 64 + b
    std::vector<uint8_t> surf, paint;   // world.h Surface, Paint
    std::vector<float> water, flowX, flowZ;  // water level (-1e9 dry) and current: empty when the chunk is dry
    std::vector<float> roadLat, roadAlong;   // trails: empty when none crosses it
    std::vector<uint8_t> roadNear;
    std::vector<TreeSpec> trees;
    std::vector<RockSpec> rocks;
    std::vector<BushSpec> bushes;
    std::vector<LogSpec> logs;
    double genMs = 0;  // how long it took to make
    uint64_t hash() const;  // of every byte above (not genMs)
};

// The smooth fields at a point (what a chunk samples every 4 m and blends between).
struct Macro {
    double h = 0;              // the land before the bumps, rivers and trails
    double drain = 0;          // the land low-passed: the level a river's water lies at (it changes slowly along it)
    double creekLevel = 0;     // ...and a creek's (less smoothed: creeks run down the hills)
    double w[PB_COUNT] = {};   // how much of each biome (sums to 1)
    double wet = 0, rug = 0, heat = 0;  // the climate
    // Rivers and creeks are where a field crosses 0.5: their signed distance from the middle of the channel (m), how much of one
    // there is here (0: none; under 0.5 a dry wash), and which way the water runs (unit, downhill on the drain).
    double riverS = 1e9, creekS = 1e9;
    double riverOn = 0, creekOn = 0;
    double flowX = 0, flowZ = 0, cflowX = 0, cflowZ = 0;
};

// The trail network: one node in every kCell x kCell cell of the world, joined to its east and north neighbours (now and then
// one is left out, and some cells have a diagonal too). An edge is a function of its two nodes alone, so the chunks either side
// of a border lay the same trail. Every node is a place (places come in phase d).
struct TrailNode {
    double x = 0, z = 0, h = 0;  // global; the flat ground's height
    int64_t i = 0, j = 0;        // its cell
    bool outpost = false, fuel = false;
};
struct TrailEdge {
    bool on = false;
    bool road = false;           // a gravel road (between outposts): wider, gentler
    int rating = 0;              // 0 green, 1 blue, 2 black
    double ax = 0, az = 0;       // where it starts (global): the samples are from here
    std::vector<float> x, z, y;  // a sample every ~2 m: offsets from (ax, az), and the graded tread's height
    std::vector<float> along;    // m from the start
    double x0 = 0, x1 = 0, z0 = 0, z1 = 0;  // its bounds (global)
    double half() const { return road ? 3.0 : 2.0; }  // the tread's half-width
};

class ProcWorld {
public:
    // The generator for a seed (made once, kept): the career's hook. A new world: ProcWorld::forSeed(ProcWorld::randomSeed()).
    static const ProcWorld& forSeed(uint64_t seed);
    static uint64_t randomSeed();  // a fresh one (from the clock and the OS)
    // Where a seed's world starts (global metres): its first outpost; and the window to build round it (a chunk corner).
    void start(int64_t& x, int64_t& z, double& yaw) const;
    void startOrigin(int64_t& ox, int64_t& oz) const;
    static void snapOrigin(double gx, double gz, int64_t& ox, int64_t& oz);  // the chunk corner nearest a global point

    uint64_t seed() const { return seed_; }
    Macro macro(double gx, double gz) const;
    double macroHeight(double gx, double gz) const;  // macro(...).h, cheaper (the far backdrop)
    int biomeAt(double gx, double gz) const;         // the biome with the most weight there
    // The trail network (procworld.h TrailNode): the node of cell (i, j), and the edge from it east (0), north (1) or north-east (2).
    TrailNode node(int64_t i, int64_t j) const;
    std::shared_ptr<const TrailEdge> edge(int64_t i, int64_t j, int dir) const;  // (cached)
    // The river and creek at a point: their channel's half-width there, and how deep the middle is.
    double riverHalfWidth(double gx, double gz) const;
    double creekHalfWidth(double gx, double gz) const;
    double riverDepth(double gx, double gz) const;
    double trailLevel(double gx, double gz) const;  // where a trail's tread lies (the land low-passed, down to the water at a ford)
    Macro land(double gx, double gz) const;         // macro() without the rivers and creeks
    // A chunk (cached: the same object for the same chunk while it's kept).
    std::shared_ptr<const Chunk> chunk(int64_t cx, int64_t cz) const;
    std::shared_ptr<Chunk> makeChunk(int64_t cx, int64_t cz) const;  // (always made afresh: the tests)
    // 0 at the start, 1 from 8 km out: rougher trails and richer caches further away.
    double remoteness(double gx, double gz) const;
    // The region a global point is in (2 x 2 km): its key ("R.<rx>.<rz>") and its name.
    static std::string regionKey(double gx, double gz);
    std::string regionName(double gx, double gz) const;

    // Window coordinates and global ones (a World(MAP_PROCEDURAL)).
    static V3 toGlobal(const World& w, const V3& local);  // (x and z: metres from the world's origin; doubles are exact far out)
    static V3 toLocal(const World& w, const V3& global);

    // (implementation)
    explicit ProcWorld(uint64_t seed);
    struct Params;
    const Params& params() const { return *params_; }

private:
    uint64_t seed_;
    std::shared_ptr<Params> params_;
};

// The chunk cache: how many chunks it holds, and dropping them all (tests).
size_t cachedChunks();
void clearChunkCache();

// The far backdrop's land past a window's edge (render.cpp sceneryHeight): the generator's macro height.
double farHeight(const World& w, double x, double z);

// Moves everything the sim holds by d (whole metres): vehicles, loose wheels, ropes, anchors, dropped parts, lines in hand.
void shiftSim(Sim& sim, const V3& d);

}  // namespace proc
